/* Writes src/model/catalog-prices.ts: the per-model prices pi-ai's pinned catalog lists for OpenAI,
   Anthropic and Google, for endpoints whose own model list publishes none. Only the prices are kept,
   so the page doesn't carry the whole catalog. tests/model/catalog.test.ts fails if the file drifts
   from the installed pi-ai.

     node scripts/catalog-prices.ts */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const SOURCES = { openai: 'openai', anthropic: 'anthropic', gemini: 'google' } as const;

interface RawCost { input: number; output: number; cacheRead?: number; cacheWrite?: number; tiers?: (RawCost & { inputTokensAbove: number })[] }

const rates = (c: RawCost) => ({
  inputPerMTok: c.input, outputPerMTok: c.output,
  ...(c.cacheRead !== undefined ? { cacheReadPerMTok: c.cacheRead } : {}),
  ...(c.cacheWrite !== undefined ? { cacheWritePerMTok: c.cacheWrite } : {})
});

export function catalogPrices(dir = `${root}node_modules/@earendil-works/pi-ai/dist/providers/data`): Record<string, Record<string, unknown>> {
  const out: Record<string, Record<string, unknown>> = {};
  for (const [preset, file] of Object.entries(SOURCES)) {
    const data = JSON.parse(readFileSync(`${dir}/${file}.json`, 'utf8')) as Record<string, Record<string, { id: string; cost?: RawCost }>>;
    const prices: Record<string, unknown> = {};
    for (const models of Object.values(data)) {
      for (const [key, m] of Object.entries(models)) {
        if (!key.startsWith('chat:') || !m.cost || prices[m.id]) continue;
        prices[m.id] = { ...rates(m.cost), ...(m.cost.tiers?.length ? { tiers: m.cost.tiers.map(t => ({ inputTokensAbove: t.inputTokensAbove, ...rates(t) })) } : {}) };
      }
    }
    out[preset] = Object.fromEntries(Object.entries(prices).sort(([a], [b]) => a.localeCompare(b)));
  }
  return out;
}

export function render(prices: Record<string, Record<string, unknown>>): string {
  return `/* Generated by scripts/catalog-prices.ts from pi-ai 1.5.2's catalog (dist/providers/data). Do not edit.
   US dollars per million tokens. Shown as the listed price in Familiar's model catalog, never as live. */
import type { Rates, PriceTier } from '@familiar/core';

export const CATALOG_PRICES: Readonly<Record<'openai' | 'anthropic' | 'gemini', Readonly<Record<string, Rates & { readonly tiers?: readonly PriceTier[] }>>>> = ${JSON.stringify(prices, null, 2)};
`;
}

if (process.argv[1]?.endsWith('catalog-prices.ts')) {
  writeFileSync(`${root}src/model/catalog-prices.ts`, render(catalogPrices()));
  console.log('wrote src/model/catalog-prices.ts');
}
